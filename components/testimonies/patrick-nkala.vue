        <p>My name is Patrick Nkala, and this is my testimony of how I came to understand the gospel
and how Jesus Christ saved me from my sins. Before becoming a Christian, my life was
marked by sin in ways that were obvious even from childhood. I used lies to escape trouble
or embarrassment, and eventually my parents struggled to trust anything I said.
Another major sin in my life was my desire to please people. I constantly sought
approval—from classmates, teachers, and especially my parents. My sense of worth
depended on how others reacted to me. When classmates mocked me for my appearance,
behaviour, or dishonesty, I internalised their comments and developed low self-esteem. I
measured myself by their opinions, and it shaped much of my early life.</p>
        <p>Other sins were also present: laziness, hatred toward certain people, stealing from my
parents, and gossip. But the most destructive and persistent was lust.</p>
        <p>Around age twelve or thirteen, my father led me in a prayer at church, and I accepted Jesus
as Lord and Saviour. I didn’t yet understand the gospel fully, but I believe God had begun a
work in me. I sensed a need for Him and knew He existed, but my understanding of Jesus
and His work was vague.</p>
        <p>At thirteen or fourteen, I began feeling deep guilt over my sin. For the first time, I prayed
habitually for forgiveness. I also prayed for things like getting out of detention or avoiding
trouble at school. I noticed that I mostly prayed when I needed help, and once the situation
improved, God became an afterthought. I rarely thanked Him or worshipped Him sincerely.
When I was fifteen, approaching sixteen, things began to change. One Christmas Eve, I had a
powerful moment with God. After listening to music, I began praying with a sincerity I had
never experienced before. I can’t remember the exact words, but I know the experience was
real. I was in my brother’s university accommodation, and that Christmas week became a
turning point.</p>
        <p>Afterward, I started seeking Christian content online and reading the Bible again—this time
with genuine desire. I read the entire New Testament on my own. I downloaded the Bible
app and explored verses daily. I also began watching preachers online. Although many of
them weren’t preaching the true gospel, the Scripture itself was what ultimately helped me
grow.</p>
        <p>After seeing a TikTok about a Christian Discord server, I joined and became one of the early
participants in their Bible studies. Hearing people my age discuss Scripture was incredibly
encouraging. I attended almost every day, often staying up until 3 or 4 a.m. because of time
zones. My parents weren’t happy about the late nights, but I was genuinely seeking God,
and the fellowship helped keep me on the right path. The COVID pandemic gave me even
more time to study Scripture and grow spiritually.
Even then, I wasn’t always sure whether I was truly saved. I searched for clarity about
salvation and eventually heard the gospel clearly preached. I realised that I had already
trusted in Jesus Christ as my Lord and Saviour. My desires had changed—I wanted to be
biblical, imitate Christ, and live a Christian life. As a result, my relationships improved, and I
developed a zeal for speaking the truth.</p>
        <p>I still fall into sin, but one thing is certain: I have been saved. I feel conviction when I sin, and
I repent and trust in Christ’s finished work. I have confidence that God hears prayers, and He
has answered many of mine. Matthew 6:25–34 became a great comfort, especially verse 33:

“But seek first the kingdom of God and his righteousness….” It reminded me not to worry
and to trust God. 2 Corinthians 1:12, which speaks of simplicity and godly sincerity, has also
been invaluable, along with the Sermon on the Mount. When I needed assurance of
salvation, I often turned to Romans chapter 8.</p>
        <p>At age 17 I moved to Chatham with my parents. I had long needed a bible based, gospel
preaching, reformed church. I used Google search to read reviews about churches in the
area. I came across a church called Enon Baptist church. I read the review: “Excellent church
teaching the truth and full gospel of Jesus Christ, something that is missing in a lot of in
churches today.” I visited the church and it was so warm. Pastor Paul Relf was very
welcoming and more than willing to answer my questions which was a breath of fresh air.
Almost a year and a half later, the time came for me to be baptised. On the 5<sup>th</sup> of February
2023, I made a public profession of my faith to the congregation and being around fellow
brothers and sisters in Christ who love me and I can love has been such a blessing. The
biblical teaching and discipleship have been such a great help to me.</p>
        <p>Daily, I am amazed at how content I am in God and how He orchestrates situations to
humble me and draw me closer to Him. I am deeply grateful for my parents, who
encouraged me to pursue Christianity while giving me space to learn. Their love, discipline,
and guidance pointed me toward God, even when I didn’t recognise it.
I thank God for what He has done in my life. His grace—shown through Christ’s death,
burial, and resurrection—has given me purpose, especially in moments when I felt
overwhelmed. I thank Him for saving me, sanctifying me, disciplining me, and reminding me
of His love. Though I am an unworthy sinner, His grace has always been sufficient and
continues to cover my sin.</p>
